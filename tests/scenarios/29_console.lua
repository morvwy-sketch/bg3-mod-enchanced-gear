-- Console commands of the server and the client.
return function(T)
    local h = T.New()
    local scrap = h:Count(h.host, "scrap")
    h:Console("server", "eg_give scrap 7")
    T.eq(h:Count(h.host, "scrap"), scrap + 7)
    h:Console("server", "eg_give all 2")
    T.eq(h:Count(h.host, "core"), 2)
    T.eq(h:Count(h.host, "gold"), 2)
    h:Console("server", "eg_give gold")
    T.eq(h:Count(h.host, "gold"), 12, "default count 10")
    h:Console("server", "eg_give nonsense")
    T.has(h.w.prints, "usage: !eg_give")
    h:Console("server", "eg_tier 3")
    T.eq(h:Data().techTier, 3)
    h:Console("server", "eg_kit")
    T.eq(h:Count(h.host, "kit"), 2)
    h:Console("server", "eg_testswords")
    T.eq(h.w:Count(h.host, h.tpl.longsword), 2, "two identical longswords")
    h:Console("server", "eg_testgear")
    T.eq(h.w:Count(h.host, h.tpl.longsword), 4)
    T.eq(h.w:Count(h.host, h.tpl.ring), 1)
    T.eq(h.w:Count(h.host, h.tpl.chainmail), 1)

    h:Rich()
    local list = h:List()
    local sword
    for _, it in ipairs(list) do if it.name == "Longsword" then sword = it.guid end end
    h:Upgrade(sword, 2)
    h:Console("server", "eg_dump")
    T.has(h.w.prints, "engine colour")
    T.has(h.w.prints, "Longsword +2")
    h:Console("server", "eg_forge")
    T.eq(h:Window().Open, true, "!eg_forge opens the window for the host")
    h:Console("client", "eg_ui")
    T.eq(h:Window().Open, false, "!eg_ui toggles")
    h:Console("client", "eg_ui")
    h:Console("client", "eg_rarity")
    T.has(h.w.prints, "forge rarity")
    h:Console("server", "eg_resync")
    T.has(h.w.prints, "all effects recalculated")
    h:Clean()
end
