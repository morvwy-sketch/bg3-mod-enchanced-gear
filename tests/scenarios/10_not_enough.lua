-- Not enough resources: nothing is charged and nothing changes.
return function(T)
    local h = T.New()
    local sword = h:Item(h.host, "longsword")
    local before = h:Bundle()
    local r = h:Req("upgrade", { item = sword })
    T.eq(r.ok, false)
    T.eq(r.reason, "resources")
    T.eq(h:Bundle(), before, "nothing charged")
    T.eq(h:State(sword), nil, "no state created")
    T.eq(h:Data().journal, nil, "no journal left")
    h:Tech(4)
    local mail = h:Item(h.host, "chainmail")
    h:Give(h.host, { gold = 1000 })
    h:Req("upgradeTo", { item = mail, target = 3 })
    local r2 = h:Req("reforge", { item = mail, affix = "VITALITY" })
    T.eq(r2.reason, "resources", "reforge without dust")
    T.eq(h:State(mail).rarity, 1)
    h:Clean()
end
