-- The state travels with the item: companion, bags; effects follow the wearer.
return function(T)
    local h = T.New()
    h:Rich()
    local mail = h:Item(h.host, "chainmail")
    h:Upgrade(mail, 5)
    h:Equip(h.host, "BODY", mail)
    T.eq(h:Statuses(h.host), { "EG_MS_BODY_5_BODY" })
    h:Unequip(h.host, "BODY")
    h.w:Move(mail, h.comp)
    h:Equip(h.comp, "BODY", mail)
    T.eq(h:Statuses(h.host), {}, "old owner lost the effect")
    T.eq(h:Statuses(h.comp), { "EG_MS_BODY_5_BODY" }, "new wearer has it")
    T.eq(h:State(mail).level, 5, "state travelled")

    h:Unequip(h.comp, "BODY")
    local bag = h:Item(h.comp, "bag")
    h.w:Move(mail, bag)
    local entry = h.Entry(h:List(), mail)
    T.ok(entry, "items in bags are listed")
    T.eq(entry.owner, h.comp)
    T.eq(entry.state.level, 5)
    T.ok(h:Req("reforge", { item = mail, affix = "VITALITY", actor = h.comp }).ok, "can be reforged from a bag")
    T.eq(h:State(mail).rarity, 2)
    h:Clean()
end
