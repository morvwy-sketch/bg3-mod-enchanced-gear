-- "Test" tab only with DevTools; access blocks (combat, no kit) shown in the header and enforced.
return function(T)
    local h = T.New()
    h:Key("F7")
    T.ok(h:Find("tabitem", "Test"), "test tab visible with DevTools")
    h:Press(h:Exact("button", "+1000 gold"))
    T.eq(h:Count(h.host, "gold"), 1000)
    h:Press(h:Exact("button", "+20 scrap, +10 dust, +5 ingots, +2 cores"))
    T.eq(h:Count(h.host, "core"), 2)
    h:Press(h:Exact("button", "IV (+20)"))
    T.eq(h:Data().techTier, 4)
    T.has(h:Texts(), "Forge technology: Tier IV (up to +20)", "header refreshed")
    h:Press(h:Exact("button", "Give test equipment"))
    T.eq(h.w:Count(h.host, h.tpl.longsword), 2)
    h:Press(h:Exact("button", "Give a smithing kit"))
    T.eq(h:Count(h.host, "kit"), 2)
    h:Press(h:Exact("button", "Recalculate all effects"))

    local h2 = T.New({ config = { DevTools = false } })
    h2:Key("F7")
    T.eq(h2:Find("tabitem", "Test"), nil, "hidden without DevTools")
    T.eq(h2:Req("dev", { what = "gold" }).reason, "devTools", "test actions refused")

    local h3 = T.New()
    local sword = h3:Item(h3.host, "longsword")
    h3:Give(h3.host, { gold = 100 })
    h3.w:E(h3.host).combat = true
    T.eq(h3:Req("upgrade", { item = sword }).reason, "combat")
    h3:Key("F7")
    h3:Click("Longsword", "selectable")
    T.has(h3:Texts(), "The forge cannot be used in combat.")
    T.eq(h3:Exact("button", "Upgrade", 2).Disabled, true, "action buttons disabled")
    h3.w:E(h3.host).combat = false
    h3.w:Take(h3.host, h3.tpl.kit, 1)
    T.eq(h3:Req("upgrade", { item = sword }).reason, "noKit")
    T.has(h3:Texts(), "A Smithing Kit is required in the party.")
    h3:Give(h3.comp, { kit = 1 })
    T.ok(h3:Req("upgrade", { item = sword }).ok, "a kit anywhere in the party is enough")
    T.ok(h3:Req("upgrade", { item = sword, actor = "nobodyhomeatall" }).ok, "unknown actor falls back to the host")
    T.eq(h3:State(sword).level, 2)
    h:Clean()
    h2:Clean()
    h3:Clean()
end
