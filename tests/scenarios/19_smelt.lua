-- Smelting: 6 scrap + 2 dust + 100 gold -> 1 refined ingot, from forge technology II.
return function(T)
    local h = T.New()
    h:Give(h.host, { scrap = 20, dust = 10, gold = 500 })
    local r = h:Req("smelt")
    T.eq(r.reason, "needTech")
    T.eq(r.params, { 2 })
    h:Tech(2)
    local before = h:Bundle()
    local ok = h:Req("smelt")
    T.ok(ok.ok, "smelted")
    T.eq(ok.msg.key, "ui.res.smelt")
    local after = h:Bundle()
    T.eq(before.scrap - after.scrap, 6)
    T.eq(before.dust - after.dust, 2)
    T.eq(before.gold - after.gold, 100)
    T.eq(after.ingot - before.ingot, 1)
    local h2 = T.New()
    h2:Tech(2)
    T.eq(h2:Req("smelt").reason, "resources")
    h:Clean()
    h2:Clean()
end
