-- Equip/unequip: effects appear and disappear exactly once, per slot, never stacking.
return function(T)
    local h = T.New()
    h:Tech(4)
    h:Rich()
    local mail = h:Item(h.host, "chainmail")
    h:Req("upgradeTo", { item = mail, target = 5 })
    T.ok(h:Req("reforge", { item = mail, affix = "VITALITY" }).ok, "reforge")
    h:Req("upgradeTo", { item = mail, target = 10 })
    T.eq(h:State(mail).level, 10)
    T.eq(h:Statuses(h.host), {}, "not equipped: no effects")
    h:Equip(h.host, "BODY", mail)
    local want = { "EG_AFX_VITALITY_1_BODY", "EG_MS_BODY_10_BODY" }
    T.eq(h:Statuses(h.host), want, "equipped")
    h:Console("server", "eg_resync")
    h:Equip(h.host, "BODY", mail)
    h.w:QueueOsiris("LongRestFinished")
    h:Pump()
    T.eq(h:Statuses(h.host), want, "repeated syncs do not stack")
    h:Unequip(h.host, "BODY")
    T.eq(h:Statuses(h.host), {}, "unequipped")

    local r1, r2 = h:Item(h.host, "ring"), h:Item(h.host, "ring")
    h:Req("upgradeTo", { item = r1, target = 5 })
    h:Req("upgradeTo", { item = r2, target = 5 })
    h:Equip(h.host, "RING1", r1)
    h:Equip(h.host, "RING2", r2)
    T.eq(h:Statuses(h.host), { "EG_MS_RING_5_RING1", "EG_MS_RING_5_RING2" }, "two rings, two statuses")
    h:Unequip(h.host, "RING1")
    T.eq(h:Statuses(h.host), { "EG_MS_RING_5_RING2" })
    h:Clean()
end
